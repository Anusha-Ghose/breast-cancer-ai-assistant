export function translatePhrase(text, targetLang) {
  if (!text || !targetLang || targetLang === 'en') return text
  const clean = String(text).toLowerCase().trim()
  const langDict = DICTIONARY[targetLang]
  if (!langDict) return text

  if (langDict[clean]) return langDict[clean]

  // Check without trailing punctuation
  const cleanNoPunct = clean.replace(/[:.?!—]+$/, '').trim()
  if (langDict[cleanNoPunct]) {
    const trailing = clean.slice(cleanNoPunct.length)
    return langDict[cleanNoPunct] + trailing
  }

  return null
}
